"""Image generation with optional Hugging Face inference and a remote fallback.

The service does not train or host a GPU model. It calls a hosted model when a
Hugging Face inference token is configured; otherwise it tries Pollinations.
Free service availability, quotas, latency, and model access can change.
"""
from __future__ import annotations

import base64
import logging
from urllib.parse import quote

import requests

from jagx_api.config import settings

logger = logging.getLogger("jagx-ai")
_MAX_IMAGE_BYTES = 12 * 1024 * 1024
_HF_MODEL = "black-forest-labs/FLUX.1-schnell"


def _valid_image(data: bytes, content_type: str = "") -> str:
    if not data or len(data) > _MAX_IMAGE_BYTES:
        raise RuntimeError("Image provider returned an empty or oversized image")
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return "image/webp"
    raise RuntimeError(f"Image provider returned unexpected content ({content_type or 'unknown type'})")


def _huggingface(prompt: str, width: int, height: int) -> tuple[bytes, str]:
    token = settings.hf_token
    if not token:
        raise RuntimeError("Hugging Face token is not configured")
    response = requests.post(
        f"https://router.huggingface.co/hf-inference/models/{_HF_MODEL}",
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        json={"inputs": prompt, "parameters": {"width": width, "height": height}},
        timeout=(10, 90),
    )
    if response.status_code != 200:
        raise RuntimeError(f"Hugging Face image provider returned HTTP {response.status_code}")
    content_type = response.headers.get("content-type", "")
    data = response.content
    mime = _valid_image(data, content_type)
    return data, mime


def _pollinations(prompt: str, width: int, height: int) -> tuple[bytes, str]:
    if not settings.pollinations_api_key:
        raise RuntimeError("Pollinations API key is not configured")
    url = "https://gen.pollinations.ai/image/" + quote(prompt[:1200], safe="")
    response = requests.get(
        url,
        params={"width": width, "height": height, "model": "flux"},
        headers={"Accept": "image/*", "User-Agent": "JagX-AI/1.0", "Authorization": f"Bearer {settings.pollinations_api_key}"},
        timeout=(10, 90),
    )
    if response.status_code != 200:
        raise RuntimeError(f"Fallback image provider returned HTTP {response.status_code}")
    mime = _valid_image(response.content, response.headers.get("content-type", ""))
    return response.content, mime


def generate(prompt: str, width: int = 768, height: int = 768) -> dict:
    prompt = (prompt or "").strip()
    if len(prompt) < 3:
        raise RuntimeError("Please provide a more detailed image prompt")
    width = max(256, min(int(width), 1024))
    height = max(256, min(int(height), 1024))
    errors = []
    providers = []
    if settings.hf_token:
        providers.append(("huggingface", _huggingface))
    if settings.pollinations_api_key:
        providers.append(("pollinations", _pollinations))
    for name, provider in providers:
        try:
            data, mime = provider(prompt, width, height)
            return {
                "provider": name,
                "model": _HF_MODEL if name == "huggingface" else "pollinations-hosted-model",
                "mime_type": mime,
                "width": width,
                "height": height,
                "image_base64": base64.b64encode(data).decode("ascii"),
                "note": "Generated by a hosted service; this backend does not train or run a GPU model.",
            }
        except Exception as exc:
            logger.warning("image provider %s failed: %s", name, exc)
            errors.append(f"{name}: {str(exc)[:160]}")
    raise RuntimeError("Image generation is temporarily unavailable. " + " | ".join(errors))
