"""Hosted video generation via Pollinations. Requires an API key; availability and free credits vary."""
from __future__ import annotations
import base64, logging
from urllib.parse import quote
import requests
from jagx_api.config import settings

logger=logging.getLogger("jagx-ai")
MAX_VIDEO_BYTES=20*1024*1024
ALLOWED_MODELS={"google/veo-3.1-fast","bytedance/seedance-1-pro-fast","alibaba/wan-2.2-fast","prunaai/p-video"}

def generate(prompt:str, duration:int=4, model:str="google/veo-3.1-fast", aspect_ratio:str="16:9")->dict:
    prompt=(prompt or "").strip()
    if len(prompt)<3: raise ValueError("Please provide a detailed video prompt")
    if len(prompt)>2000: raise ValueError("Video prompt exceeds 2000 characters")
    duration=max(2,min(int(duration),8))
    if model not in ALLOWED_MODELS: raise ValueError("Unsupported video model. Choose an approved model.")
    key=getattr(settings,"pollinations_api_key","")
    if not key: raise RuntimeError("Video generation is not configured. Add POLLINATIONS_API_KEY in Render.")
    url="https://gen.pollinations.ai/video/"+quote(prompt,safe="")
    response=requests.get(url,params={"model":model,"duration":duration,"aspectRatio":aspect_ratio},
                          headers={"Authorization":"Bearer "+key,"Accept":"video/mp4"},
                          timeout=(10,290),stream=True)
    try:
        if response.status_code!=200:
            raise RuntimeError("Video provider returned HTTP "+str(response.status_code))
        content_type=response.headers.get("content-type","").lower()
        data=bytearray()
        for chunk in response.iter_content(chunk_size=64*1024):
            if not chunk: continue
            data.extend(chunk)
            if len(data)>MAX_VIDEO_BYTES: raise RuntimeError("Generated video exceeded the 20 MB response limit")
        raw=bytes(data)
        if not raw or not (raw[4:8]==b"ftyp" or "video/mp4" in content_type):
            raise RuntimeError("Video provider did not return a valid MP4")
        return {"provider":"pollinations","model":model,"mime_type":"video/mp4","duration_seconds":duration,
                "video_base64":base64.b64encode(raw).decode("ascii"),
                "note":"Generated by a hosted provider. Free credits, model access and quotas are not guaranteed."}
    finally:
        response.close()
